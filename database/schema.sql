-- Grau-Alert | PostgreSQL / Supabase
-- Ejecutar una sola vez en el SQL Editor del proyecto Supabase.
-- El backend PHP usa PDO con una conexión privada a PostgreSQL.

create extension if not exists pgcrypto;

create table if not exists public.usuarios (
    id uuid primary key default gen_random_uuid(),
    correo text not null unique,
    password_hash text not null,
    nombres text not null,
    apellidos text not null,
    rol text not null check (rol in ('administrador', 'auxiliar', 'tutor', 'apoderado')),
    telefono text,
    activo boolean not null default true,
    creado_en timestamptz not null default now(),
    actualizado_en timestamptz not null default now()
);

create table if not exists public.grados (
    id bigint generated by default as identity primary key,
    nombre text not null unique,
    nivel text not null default 'secundaria',
    seccion text,
    activo boolean not null default true,
    creado_en timestamptz not null default now()
);

create table if not exists public.estudiantes (
    id uuid primary key default gen_random_uuid(),
    codigo text not null unique,
    nombres text not null,
    apellidos text not null,
    grado_id bigint references public.grados(id) on delete set null,
    foto_url text,
    qr_token uuid not null unique default gen_random_uuid(),
    activo boolean not null default true,
    creado_en timestamptz not null default now(),
    actualizado_en timestamptz not null default now()
);

-- Ampliaciones idempotentes para importar el directorio existente del colegio.
alter table public.estudiantes add column if not exists nombre_completo text;
alter table public.estudiantes add column if not exists telefono_apoderado text;
alter table public.estudiantes add column if not exists dni varchar(8);
alter table public.estudiantes add column if not exists correo text;
alter table public.estudiantes add column if not exists inicio_sesion_perueduca boolean;
create unique index if not exists ux_estudiantes_dni on public.estudiantes (dni) where dni is not null and dni <> '';
update public.estudiantes
set nombre_completo = nullif(trim(concat_ws(' ', nombres, apellidos)), '')
where nombre_completo is null;

create table if not exists public.estudiante_apoderados (
    estudiante_id uuid not null references public.estudiantes(id) on delete cascade,
    apoderado_id uuid not null references public.usuarios(id) on delete cascade,
    parentesco text,
    contacto_principal boolean not null default false,
    creado_en timestamptz not null default now(),
    primary key (estudiante_id, apoderado_id)
);

create table if not exists public.asistencias (
    id uuid primary key default gen_random_uuid(),
    estudiante_id uuid not null references public.estudiantes(id) on delete restrict,
    fecha date not null default (now() at time zone 'America/Lima')::date,
    hora_ingreso timestamptz not null default now(),
    hora_salida timestamptz,
    estado text not null default 'presente' check (estado in ('presente', 'tardanza', 'justificada', 'falta')),
    metodo text not null default 'qr' check (metodo in ('qr', 'manual')),
    verificado_por uuid references public.usuarios(id) on delete set null,
    observacion text,
    creado_en timestamptz not null default now(),
    unique (estudiante_id, fecha)
);

create table if not exists public.calendario_escolar (
    fecha date primary key,
    estado text not null check (estado in ('lectivo', 'feriado', 'vacaciones', 'suspension')),
    evento text not null,
    alarma_activa boolean not null default true,
    creado_por uuid references public.usuarios(id) on delete set null,
    creado_en timestamptz not null default now(),
    actualizado_en timestamptz not null default now()
);

create table if not exists public.alertas (
    id uuid primary key default gen_random_uuid(),
    estudiante_id uuid not null references public.estudiantes(id) on delete cascade,
    asistencia_id uuid references public.asistencias(id) on delete set null,
    apoderado_id uuid references public.usuarios(id) on delete set null,
    tipo text not null check (tipo in ('ingreso', 'tardanza', 'inasistencia', 'incidencia', 'salida')),
    canal text not null default 'pendiente' check (canal in ('pendiente', 'correo', 'sms', 'whatsapp', 'panel')),
    estado text not null default 'pendiente' check (estado in ('pendiente', 'enviada', 'fallida', 'omitida')),
    mensaje text not null,
    enviada_en timestamptz,
    creado_en timestamptz not null default now()
);

create index if not exists idx_estudiantes_grado_activo on public.estudiantes (grado_id, activo);
create index if not exists idx_asistencias_fecha on public.asistencias (fecha desc);
create index if not exists idx_asistencias_estudiante_fecha on public.asistencias (estudiante_id, fecha desc);
create index if not exists idx_alertas_estado_fecha on public.alertas (estado, creado_en desc);
create index if not exists idx_estudiante_apoderados_apoderado on public.estudiante_apoderados (apoderado_id);
create index if not exists idx_calendario_estado_fecha on public.calendario_escolar (estado, fecha);

create or replace function public.actualizar_timestamp()
returns trigger
language plpgsql
as $$
begin
    new.actualizado_en = now();
    if tg_table_name = 'estudiantes' then
        if new.nombre_completo is null or trim(new.nombre_completo) = '' then
            new.nombre_completo = nullif(trim(concat_ws(' ', new.nombres, new.apellidos)), '');
        end if;
    end if;
    return new;
end;
$$;

drop trigger if exists estudiantes_actualizado_en on public.estudiantes;
create trigger estudiantes_actualizado_en before update on public.estudiantes
for each row execute function public.actualizar_timestamp();

drop trigger if exists usuarios_actualizado_en on public.usuarios;
create trigger usuarios_actualizado_en before update on public.usuarios
for each row execute function public.actualizar_timestamp();

drop trigger if exists calendario_actualizado_en on public.calendario_escolar;
create trigger calendario_actualizado_en before update on public.calendario_escolar
for each row execute function public.actualizar_timestamp();

