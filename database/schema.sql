-- Bloquea el acceso directo de cualquier rol a las tablas. PUBLIC es un rol
-- especial disponible tanto en PostgreSQL estándar como en Supabase. La app PHP
-- se conecta como propietario de las tablas, por lo que puede operar con PDO.
do $$
declare tabla text;
begin
    foreach tabla in array array['usuarios','grados','estudiantes','estudiante_apoderados','asistencias','calendario_escolar','alertas'] loop
        execute format('drop policy if exists bloquear_api_publica on public.%I', tabla);
        execute format('create policy bloquear_api_publica on public.%I for all to public using (false) with check (false)', tabla);
    end loop;
end;
$$;

